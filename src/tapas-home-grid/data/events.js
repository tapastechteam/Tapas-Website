export function albumUrl(event, galleryHref) {
  const [base, fragment] = galleryHref.split("#");
  const separator = base.includes("?") ? "&" : "?";
  return base + separator + "event=" + encodeURIComponent(event.id) + (fragment ? "#" + fragment : "");
}
